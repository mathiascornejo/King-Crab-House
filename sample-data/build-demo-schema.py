"""Builds demo-schema.sql: the whole app (tables, functions, policies) in a separate `demo` schema for the test
version, with the current menu copied from the live one. Rebuild after changing supabase.sql:
    python3 -I sample-data/build-demo-schema.py
"""
from pathlib import Path

root = Path(__file__).resolve().parent.parent
app = (root / 'supabase.sql').read_text()
assert 'public.' not in app, 'supabase.sql names the public schema directly; those lines would escape the demo schema'
app = app.replace('search_path = public', 'search_path = demo')

(root / 'sample-data' / 'demo-schema.sql').write_text(f"""-- Generated by sample-data/build-demo-schema.py — the test version's own copy of the app in schema `demo`.
begin;
create schema if not exists demo;
grant usage on schema demo to anon, authenticated, service_role;
-- same default privileges Supabase gives the public schema; supabase.sql then revokes/grants on top, as it does there
alter default privileges in schema demo grant all on tables to anon, authenticated, service_role;
alter default privileges in schema demo grant all on sequences to anon, authenticated, service_role;
alter default privileges in schema demo grant all on functions to anon, authenticated, service_role;
set local search_path = demo;

{app}

-- the current menu, recipes and costs instead of supabase.sql's starter menu
delete from demo.recipe_ingredients; delete from demo.ingredient_costs; delete from demo.recipes; delete from demo.ingredients;
insert into demo.ingredients (id, name, unit, stock, min_stock, batch_tracked) select id, name, unit, 0, 0, batch_tracked from public.ingredients;
insert into demo.recipes (id, name, category, price, pricing, archived_at) select id, name, category, price, pricing, archived_at from public.recipes;
insert into demo.recipe_ingredients (recipe_id, ingredient_id, qty) select recipe_id, ingredient_id, qty from public.recipe_ingredients;
insert into demo.ingredient_costs (ingredient_id, cost, estimated) select ingredient_id, cost, estimated from public.ingredient_costs;

-- let the API serve the demo schema (the page asks for it with Accept-Profile / Content-Profile: demo)
alter role authenticator set pgrst.db_schemas = 'public, graphql_public, demo';
commit;
notify pgrst, 'reload config';
notify pgrst, 'reload schema';
""")
print('wrote sample-data/demo-schema.sql')
